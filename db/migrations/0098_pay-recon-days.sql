-- Up Migration
-- Reconciled bill days of the T+1 collection reconciliation (08 BR-PAY-07 每日 T+1 用渠道的交易账单逐笔
-- 核对; B2-15m money review r2 S2: every new worker process restarted each App's daily bill.recon
-- chain at its first bill day, downloading every past bill again). Task B2-15n.
-- Compatibility: additive. One new empty table, named constraints, the append-only guard trigger
-- (app.reject_update_delete() of 0003), grants.
-- Recovery: restore from backup; no down migration.
--
-- pay_recon_days: one row per (app_id, pay_channel, bill_date) whose channel bill a bill.recon run
--   reconciled to the end (the bill downloaded, read, every line checked and its PAY_FEE booked);
--   a bill not available or refused as malformed leaves no row. Written only by the payment module
--   (apps/api/src/modules/payment, on the run's transaction, idempotent through
--   pay_recon_days_day_key and ON CONFLICT DO NOTHING); never updated or deleted. The seed of the
--   daily chain reads, per App, the last reconciled bill day of each channel and starts the chain
--   at the day after the earliest of them. bill_date is the +08:00 accounting day of the bill
--   (@couli/domain); reconciled_at is the injected clock's instant of the first run that
--   reconciled it; created_at is the technical insert time. id is generated by the application.
-- Retention: none here.
--
-- Grants: couli_app SELECT, INSERT (no UPDATE / DELETE: insert-only, the trigger rejects both for
-- every role as a second line of defence); couli_readonly SELECT. couli_payout and couli_maint get
-- nothing (BR-PAY-08 ①).
--
-- Timeouts: only a new, empty table and its trigger are created; short catalog locks only. 5s
-- lock wait so a blocked deploy fails fast, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.pay_recon_days (
  id            uuid NOT NULL,
  app_id        text NOT NULL,
  pay_channel   text NOT NULL,
  bill_date     date NOT NULL,
  reconciled_at timestamptz NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pay_recon_days_pkey PRIMARY KEY (id),
  CONSTRAINT pay_recon_days_day_key UNIQUE (app_id, pay_channel, bill_date),
  CONSTRAINT pay_recon_days_app_id_check CHECK (app_id <> ''),
  CONSTRAINT pay_recon_days_pay_channel_check CHECK (pay_channel IN ('wechat_pay', 'alipay'))
);

CREATE TRIGGER pay_recon_days_append_only
  BEFORE UPDATE OR DELETE ON app.pay_recon_days
  FOR EACH ROW EXECUTE FUNCTION app.reject_update_delete();

GRANT SELECT, INSERT ON app.pay_recon_days TO couli_app;
GRANT SELECT ON app.pay_recon_days TO couli_readonly;
