-- Up Migration
-- settle_runs: settlement's own run-level state of a monthly-bill confirmation (规划/04 §3.2
-- settle_runs, couli #236; orchestrator ruling D10-492, 2026-10-31; 08 BR-FUND-04 ⑦, BR-TEXT-09
-- CREDITED idempotency key settle_run_id:part). Task B2-04zfa; the readers and writers are B2-04zf
-- (settle.run_done), which so no longer reads event_log (02 §11: audit only, consumers never read).
-- Compatibility: additive. One new empty table with named constraints and index, and grants; no
-- existing object changes, no backfill (the foreign key takes a SHARE ROW EXCLUSIVE lock on
-- settle_bills while it is added).
-- Recovery: restore from backup; no down migration.
--
-- settle_runs: one row per settle run (one confirmation of a bill). settle_run_id is the primary
--   key and the same value as settle_batches.settle_run_id; it is generated by the application (no
--   SQL default). (app_id, bill_id) points to the run's bill in settle_bills (no cascade).
--   part: how many executions of the run have been published (normally 1, 2… after a resume),
--   0 until the first settle.run_done. last_outcome: done / partial of the last published
--   execution, null until then. part_started_at: the start of the current execution, taken from
--   the injected Clock (no database default); 「本次执行是否有入账」 is answered from settlement's
--   own batches and items since this instant. A publish is a CAS on row_version (SET part,
--   last_outcome, part_started_at, row_version = row_version + 1, updated_at WHERE … AND
--   row_version = :read) in the same transaction as the settle.run_done outbox row.
--   settle_run_id, app_id, bill_id and created_at never change; rows are never deleted.
-- Writer: settlement (couli_app).
--
-- Grants: couli_app SELECT, INSERT and column UPDATE of part, last_outcome, part_started_at,
-- row_version, updated_at (no DELETE / TRUNCATE). No other role gets any privilege (D10-492 ②).
--
-- Timeouts: only a new, empty table and its index are created; short catalog locks only. 5s lock
-- wait so a blocked deploy fails fast, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.settle_runs (
  settle_run_id   uuid NOT NULL,
  app_id          text NOT NULL,
  bill_id         text NOT NULL,
  part            integer NOT NULL DEFAULT 0,
  last_outcome    text,
  part_started_at timestamptz NOT NULL,
  row_version     integer NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT settle_runs_pkey PRIMARY KEY (settle_run_id),
  CONSTRAINT settle_runs_bill_fkey FOREIGN KEY (app_id, bill_id)
    REFERENCES app.settle_bills (app_id, bill_id),
  CONSTRAINT settle_runs_app_id_check CHECK (app_id <> ''),
  CONSTRAINT settle_runs_part_check CHECK (part >= 0),
  CONSTRAINT settle_runs_last_outcome_check CHECK (last_outcome IN ('done', 'partial')),
  CONSTRAINT settle_runs_row_version_check CHECK (row_version >= 0)
);

CREATE INDEX settle_runs_bill_idx ON app.settle_runs (app_id, bill_id);

GRANT SELECT, INSERT ON app.settle_runs TO couli_app;
GRANT UPDATE (part, last_outcome, part_started_at, row_version, updated_at)
  ON app.settle_runs TO couli_app;
