-- Up Migration
-- Personal-data copy requests and the isolated store of identities replaced by a real-name
-- correction (规划/04 §3.2 personal_data_copies and 实名更正旧身份, §2.5 enums; BR-ID-40 细则,
-- BR-ID-25 旧身份留存, BR-ID-28; contract line CT-24q, contracts/enums/identity.yaml
-- personal_data_copy_delivery / personal_data_copy_status). Task B1-27d (task brief §9 ①–⑥),
-- prerequisite of B1-27a / B1-27c / B1-27h. Storage and grants only: registration, generation,
-- delivery, expiry, cancellation and the correction flow are written by the identity services.
-- Compatibility: additive, two new empty tables; no existing object changes. The file number is a
-- placeholder taken at landing time (D10-116); nothing below depends on it.
-- Recovery: restore from backup; no down migration. (Until a later release writes to them, the two
-- tables could be dropped by a new migration.)
--
-- app.personal_data_copies: one row per registered copy request (BR-ID-40). Columns:
--   id              uuid         UUIDv7 generated by the application (no SQL default, rule 6); it is
--                   also the external number (export_id on the admin side, copy_id in the app).
--   app_id, user_id the member the copy is for (FK app.users (app_id, id), same app only).
--   requested_by    the admin who registered it (FK app.admin_users (app_id, id), same app only).
--   delivery        in_app_sms / wecom_session (CHECK, contract enum).
--   status          pending / running / ready / delivered / failed / expired / cancelled (CHECK,
--                   contract enum); no default, the writer always states it.
--   retry_of        a failed earlier request this one re-registers (FK to (app_id, id) of this
--                   table, same app only); the retry keeps that request's due_at (written by the
--                   application).
--   object_key      storage key of the generated file; cleared when the file is deleted.
--   due_at          statutory deadline of the request (required).
--   generated_at, delivered_at, expires_at   lifecycle instants from the injected Clock.
--   failure_reason  why generation or delivery failed.
--   row_version, created_at, updated_at   as on the other identity tables.
--   No column holds the request reason, the identity-check conclusion, the two channel facts,
--   the extraction code or the one-time password: those go to audit_logs only and the password
--   is never stored (04 §3.2).
-- One unfinished request per member: partial unique index (app_id, user_id) WHERE status IN
-- (pending, running, ready); finished history repeats freely. Reads by member and the foreign-key
-- checks use the plain (app_id, user_id) index; the registrant and retry_of keys have their own.
-- Cross-column lifecycle rules (e.g. ready needs object_key) are left to the single writer.
--
-- app.realname_prior_identities: one row per identity replaced by a real-name correction
-- (BR-ID-25). Insert-only history with no surrogate key: a member may collect several rows over
-- successive corrections. Columns: app_id, user_id (FK app.users (app_id, id)); name_cipher and
-- id_no_cipher (ciphertext under the separate prior-identity key ring of B1-27e); id_no_hmac
-- (lowercase hex SHA-256 digest, same format as app.realname); verified_at of the replaced
-- identity; corrected_at (when the correction replaced it); created_at. All NOT NULL. Rows are
-- not removed early when the account is deleted (BR-ID-28); a viewing endpoint and permission are
-- a separate task, so no runtime role can read the table yet.
-- No foreign key cascades.
--
-- Grants:
--   personal_data_copies: couli_app SELECT / INSERT and column UPDATE on exactly status,
--     object_key, generated_at, delivered_at, expires_at, failure_reason, row_version, updated_at;
--     no table-wide UPDATE, no DELETE or TRUNCATE (id, app_id, user_id, requested_by, delivery,
--     retry_of, due_at and created_at never change). couli_readonly gets column SELECT on every
--     column except object_key (the file location stays with the service); a later migration that
--     adds a column grants it to couli_readonly explicitly. couli_payout and couli_maint get nothing.
--   realname_prior_identities: couli_app INSERT only (no SELECT, so not even RETURNING; no UPDATE /
--     DELETE / TRUNCATE). Every other runtime role gets nothing.
--
-- Timeouts: CREATE TABLE / INDEX on new empty tables are instant; the foreign keys take SHARE ROW
-- EXCLUSIVE on app.users and app.admin_users, held to commit. 5s lock wait so a blocked deploy
-- fails fast instead of queueing sign-ins and admin writes behind it; 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.personal_data_copies (
  id             uuid NOT NULL,
  app_id         text NOT NULL,
  user_id        uuid NOT NULL,
  requested_by   uuid NOT NULL,
  delivery       text NOT NULL,
  status         text NOT NULL,
  retry_of       uuid,
  object_key     text,
  due_at         timestamptz NOT NULL,
  generated_at   timestamptz,
  delivered_at   timestamptz,
  expires_at     timestamptz,
  failure_reason text,
  row_version    integer NOT NULL DEFAULT 0,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT personal_data_copies_pkey PRIMARY KEY (id),
  CONSTRAINT personal_data_copies_app_id_id_key UNIQUE (app_id, id),
  CONSTRAINT personal_data_copies_user_fkey FOREIGN KEY (app_id, user_id)
    REFERENCES app.users (app_id, id),
  CONSTRAINT personal_data_copies_requested_by_fkey FOREIGN KEY (app_id, requested_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT personal_data_copies_retry_of_fkey FOREIGN KEY (app_id, retry_of)
    REFERENCES app.personal_data_copies (app_id, id),
  CONSTRAINT personal_data_copies_delivery_check
    CHECK (delivery IN ('in_app_sms', 'wecom_session')),
  CONSTRAINT personal_data_copies_status_check CHECK (
    status IN ('pending', 'running', 'ready', 'delivered', 'failed', 'expired', 'cancelled')
  ),
  CONSTRAINT personal_data_copies_object_key_check
    CHECK (object_key IS NULL OR object_key ~ '[^[:space:]]'),
  CONSTRAINT personal_data_copies_failure_reason_check
    CHECK (failure_reason IS NULL OR failure_reason ~ '[^[:space:]]'),
  CONSTRAINT personal_data_copies_row_version_check CHECK (row_version >= 0)
);

CREATE UNIQUE INDEX personal_data_copies_open_key
  ON app.personal_data_copies (app_id, user_id)
  WHERE status IN ('pending', 'running', 'ready');

CREATE INDEX personal_data_copies_user_idx
  ON app.personal_data_copies (app_id, user_id);

CREATE INDEX personal_data_copies_requested_by_idx
  ON app.personal_data_copies (app_id, requested_by);

CREATE INDEX personal_data_copies_retry_of_idx
  ON app.personal_data_copies (app_id, retry_of)
  WHERE retry_of IS NOT NULL;

GRANT SELECT, INSERT ON app.personal_data_copies TO couli_app;
GRANT UPDATE (status, object_key, generated_at, delivered_at, expires_at, failure_reason,
  row_version, updated_at)
  ON app.personal_data_copies TO couli_app;
GRANT SELECT (id, app_id, user_id, requested_by, delivery, status, retry_of, due_at, generated_at,
  delivered_at, expires_at, failure_reason, row_version, created_at, updated_at)
  ON app.personal_data_copies TO couli_readonly;

CREATE TABLE app.realname_prior_identities (
  app_id       text NOT NULL,
  user_id      uuid NOT NULL,
  name_cipher  bytea NOT NULL,
  id_no_cipher bytea NOT NULL,
  id_no_hmac   text NOT NULL,
  verified_at  timestamptz NOT NULL,
  corrected_at timestamptz NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT realname_prior_identities_user_fkey FOREIGN KEY (app_id, user_id)
    REFERENCES app.users (app_id, id),
  CONSTRAINT realname_prior_identities_id_no_hmac_check CHECK (id_no_hmac ~ '^[0-9a-f]{64}$')
);

CREATE INDEX realname_prior_identities_user_idx
  ON app.realname_prior_identities (app_id, user_id);

GRANT INSERT ON app.realname_prior_identities TO couli_app;
