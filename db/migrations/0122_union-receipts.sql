-- Up Migration
-- union_receipts: one row per union collection entered by finance or confirmed by R1 (规划/04 §3.2
-- union_receipts; 08 BR-FUND-20 细则「联盟回款凭证」; orchestrator rulings D10-538, D10-589). Task
-- B2-04zh; the writers and readers are B2-04zr.
-- Compatibility: additive. One new empty table with named constraints and indexes, and grants; no
-- existing object changes, no backfill (the foreign keys take SHARE ROW EXCLUSIVE locks on
-- ledger_vouchers and admin_users while they are added).
-- Recovery: restore from backup; no down migration.
--
-- union_receipts: receipt_id is the primary key and the {receipt_id} of the voucher key
--   RECEIPT:{platform}:{receipt_id}; it is generated by the application (no SQL default). There is
--   no business key: the same platform, day and amount can be two real collections.
--   amount_fen is the amount that actually arrived, not the receivable, and stays as entered after
--   a reversal. created_by is required for ADMIN_ENTRY and may be null for R1_RECON.
--   A record is reversed as a whole and at most once: reversed_at, reversed_by and
--   reversal_voucher_id are set together in the transaction of the reversal voucher, by a compare
--   on reversed_at IS NULL under the row lock (B2-04zr); the unique key on reversal_voucher_id and
--   the voucher's own uniq_key back that up. Rows are never deleted.
-- Writer: settlement (couli_app), through the ledger command UNION_RECEIPT.
--
-- Grants: couli_app SELECT, INSERT and column UPDATE of the three reversal columns (no DELETE /
-- TRUNCATE); couli_readonly SELECT (D10-589). No other role gets any privilege.
--
-- Timeouts: only a new, empty table and its indexes are created; short catalog locks only. 5s lock
-- wait so a blocked deploy fails fast, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.union_receipts (
  receipt_id          uuid NOT NULL,
  app_id              text NOT NULL,
  platform            text NOT NULL,
  receipt_date        date NOT NULL,
  amount_fen          bigint NOT NULL,
  method              text NOT NULL,
  cash_account        text NOT NULL,
  voucher_id          uuid NOT NULL,
  note                text,
  created_by          uuid,
  created_at          timestamptz NOT NULL DEFAULT now(),
  reversed_at         timestamptz,
  reversed_by         uuid,
  reversal_voucher_id uuid,
  CONSTRAINT union_receipts_pkey PRIMARY KEY (receipt_id),
  CONSTRAINT union_receipts_voucher_key UNIQUE (app_id, voucher_id),
  CONSTRAINT union_receipts_reversal_voucher_key UNIQUE (app_id, reversal_voucher_id),
  CONSTRAINT union_receipts_voucher_fkey FOREIGN KEY (app_id, voucher_id)
    REFERENCES app.ledger_vouchers (app_id, id),
  CONSTRAINT union_receipts_reversal_voucher_fkey FOREIGN KEY (app_id, reversal_voucher_id)
    REFERENCES app.ledger_vouchers (app_id, id),
  CONSTRAINT union_receipts_created_by_fkey FOREIGN KEY (app_id, created_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT union_receipts_reversed_by_fkey FOREIGN KEY (app_id, reversed_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT union_receipts_app_id_check CHECK (app_id <> ''),
  CONSTRAINT union_receipts_platform_check CHECK (
    platform IN ('taobao', 'jd', 'pdd', 'meituan', 'vip', 'douyin', 'eleme', 'kuaishou', 'suning')
  ),
  CONSTRAINT union_receipts_amount_fen_check CHECK (amount_fen > 0),
  CONSTRAINT union_receipts_method_check CHECK (method IN ('ADMIN_ENTRY', 'R1_RECON')),
  CONSTRAINT union_receipts_cash_account_check CHECK (cash_account IN ('CASH_ALIPAY', 'CASH_BANK')),
  CONSTRAINT union_receipts_note_check CHECK (char_length(note) <= 500),
  CONSTRAINT union_receipts_created_by_check CHECK (method <> 'ADMIN_ENTRY' OR created_by IS NOT NULL),
  CONSTRAINT union_receipts_reversal_check CHECK (
    (reversed_at IS NULL AND reversed_by IS NULL AND reversal_voucher_id IS NULL)
    OR (reversed_at IS NOT NULL AND reversed_by IS NOT NULL AND reversal_voucher_id IS NOT NULL)
  )
);

-- adminListUnionReceipts: receipt_date, then created_at, then receipt_id, all descending, with an
-- optional platform filter and an optional date range.
CREATE INDEX union_receipts_list_idx
  ON app.union_receipts (app_id, receipt_date DESC, created_at DESC, receipt_id DESC);
CREATE INDEX union_receipts_platform_list_idx
  ON app.union_receipts (app_id, platform, receipt_date DESC, created_at DESC, receipt_id DESC);

GRANT SELECT, INSERT ON app.union_receipts TO couli_app;
GRANT UPDATE (reversed_at, reversed_by, reversal_voucher_id) ON app.union_receipts TO couli_app;
GRANT SELECT ON app.union_receipts TO couli_readonly;
