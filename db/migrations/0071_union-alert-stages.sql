-- Up Migration
-- Union authorization expiry: estimated-expiry flag, configurable reminder stages and the admin
-- re-authorization session table (08 BR-ID-24 正文 ②③ and 细则「后台联盟账号列表」「后台告警手机号与
-- 重新授权会话」, orchestrator rulings D10-152 / D10-159; 规划/04 §3.2 union_accounts and
-- admin_union_auth_sessions; 12 §9 T-05). Task B1-22a (task brief §9). Storage only: OAuth, the
-- ten-minute lifetime, probes, SMS and audit are written by the union services.
-- Compatibility: additive on app.union_accounts plus one new table; nothing is dropped for good.
--   union_accounts.auth_expires_estimated  boolean NOT NULL DEFAULT false. true when the union
--     returned no expiry and auth_expires_at was estimated as authorization moment + 90 days
--     (BR-ID-24 细则, shown as 「估算」 in the admin list). The constant default fills existing rows
--     without a rewrite (PG 11+), and every existing row is a real expiry or none at all, so false
--     is correct for them. The default stays: writers that do not estimate may omit the column.
--   union_accounts_alert_stage_check  dropped and added back under the same name with a wider
--     domain: none / expired as before, plus d<N> for N = 1–999 without a leading zero
--     (^d[1-9][0-9]{0,2}$), so changing union.auth_alert_days (default 14, 7, 1) never needs a
--     migration. The five old values (none, d14, d7, d1, expired) all satisfy the new CHECK, so no
--     existing row can violate it. It is added NOT VALID: new rows and updates are checked at once;
--     validating it needs its own migration (precedent 0057 / 0058), because a VALIDATE in the same
--     transaction is refused by squawk (constraint-missing-not-valid) and union_accounts, an
--     attribution table, takes no squawk exception. The default stays 'none'. auth_status is unchanged.
--   union_credentials and every other existing object are unchanged.
-- Guard: union_accounts is a funds / attribution table (prefix union_ in tools/ci/lint-migrations.ts);
-- its alert_stage CHECK is rebuilt under the same name with a different definition, so this file
-- must be registered by name and sha256 in APPROVED_GUARD_CHANGES of that script (class-3 protected
-- path: two reviews and the approval label). Any later edit of this file needs a new registration.
-- Recovery: restore from backup; no down migration. (Narrowing back would be a new migration that,
-- after the application stops writing other d<N> stages and those rows are reset, restores the
-- five-value CHECK, and, once nothing reads them, drops the session table and the new column.)
--
-- admin_union_auth_sessions: one row per admin re-authorization attempt (BR-ID-24 ③; all OAuth
-- platforms, reauth_mode = oauth). Writer: union. Columns:
--   id                uuid         UUIDv7 generated by the application (no SQL default, rule 6).
--   app_id, union_account_id      target union account (FK app.union_accounts (app_id, id), so a
--                     session can only point at an account of its own app).
--   state_hash        bytea        SHA-256 of the OAuth state (exactly 32 bytes, CHECK); the plain
--                     state is never stored. Unique across all apps: the callback looks a session
--                     up by the hash alone.
--   created_by        uuid         the admin who started it (FK app.admin_users (app_id, id), same
--                     app only).
--   expires_at        when the state stops being accepted (created_at + 10 minutes by default, set by
--                     the application); strictly after created_at (CHECK).
--   used_at           when the callback claimed the state (single use: B1-22c claims with a
--                     conditional update on status = 'pending' AND used_at IS NULL).
--   status            pending (default) / succeeded / failed / expired.
--   error             failure reason of a failed callback; an expired session may keep a reason.
--   created_at, finished_at, updated_at   application clock, no SQL default (task brief §9).
-- Lifecycle CHECK (admin_union_auth_sessions_lifecycle_check):
--   pending    finished_at and error NULL (used_at either: claimed, exchange still running);
--   succeeded  used_at and finished_at set, error NULL;
--   failed     used_at, finished_at and error set (only a callback can fail a session);
--   expired    used_at NULL, finished_at set (error either).
-- Reads: the expiry sweep uses the partial index on expires_at WHERE status = 'pending'; the
-- account page and the initiating admin use the two foreign-key indexes; result polling and the
-- callback use the primary key and the state_hash unique key.
-- No foreign key cascades; no DELETE or TRUNCATE for any business role (sessions are history).
--
-- Grants: couli_app gets SELECT / INSERT / UPDATE on the new table (no DELETE). couli_readonly gets
-- column-level SELECT on every column except state_hash, so processes reading through the
-- read-only role never see the state digest; a later migration that adds a column must grant it to
-- couli_readonly explicitly. couli_payout and couli_maint get nothing. On union_accounts the
-- table-level grants of 0015 (couli_app SELECT / INSERT / UPDATE, couli_readonly SELECT) already
-- cover the new column, so no GRANT is needed there.
--
-- Timeouts: ADD COLUMN with a constant default is catalog-only; DROP / ADD CONSTRAINT (NOT VALID,
-- no scan) take ACCESS EXCLUSIVE on app.union_accounts, held to commit (the runner uses one
-- transaction); the new table's foreign keys take SHARE ROW EXCLUSIVE on app.union_accounts and
-- app.admin_users; CREATE TABLE / INDEX on an empty table are instant. 5s lock wait so a blocked
-- deploy fails fast instead of queueing union traffic behind it; 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

ALTER TABLE app.union_accounts
  ADD COLUMN auth_expires_estimated boolean NOT NULL DEFAULT false;

ALTER TABLE app.union_accounts DROP CONSTRAINT union_accounts_alert_stage_check;

ALTER TABLE app.union_accounts ADD CONSTRAINT union_accounts_alert_stage_check
  CHECK (alert_stage IN ('none', 'expired') OR alert_stage ~ '^d[1-9][0-9]{0,2}$') NOT VALID;

CREATE TABLE app.admin_union_auth_sessions (
  id               uuid NOT NULL,
  app_id           text NOT NULL,
  union_account_id uuid NOT NULL,
  state_hash       bytea NOT NULL,
  created_by       uuid NOT NULL,
  expires_at       timestamptz NOT NULL,
  used_at          timestamptz,
  status           text NOT NULL DEFAULT 'pending',
  error            text,
  created_at       timestamptz NOT NULL,
  finished_at      timestamptz,
  updated_at       timestamptz NOT NULL,
  CONSTRAINT admin_union_auth_sessions_pkey PRIMARY KEY (id),
  CONSTRAINT admin_union_auth_sessions_state_hash_key UNIQUE (state_hash),
  CONSTRAINT admin_union_auth_sessions_account_fkey FOREIGN KEY (app_id, union_account_id)
    REFERENCES app.union_accounts (app_id, id),
  CONSTRAINT admin_union_auth_sessions_created_by_fkey FOREIGN KEY (app_id, created_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT admin_union_auth_sessions_state_hash_check CHECK (octet_length(state_hash) = 32),
  CONSTRAINT admin_union_auth_sessions_status_check
    CHECK (status IN ('pending', 'succeeded', 'failed', 'expired')),
  CONSTRAINT admin_union_auth_sessions_lifecycle_check CHECK (
    (status = 'pending' AND finished_at IS NULL AND error IS NULL)
    OR (status = 'succeeded' AND used_at IS NOT NULL AND finished_at IS NOT NULL
      AND error IS NULL)
    OR (status = 'failed' AND used_at IS NOT NULL AND finished_at IS NOT NULL
      AND error IS NOT NULL)
    OR (status = 'expired' AND used_at IS NULL AND finished_at IS NOT NULL)
  ),
  CONSTRAINT admin_union_auth_sessions_expiry_check CHECK (expires_at > created_at)
);

CREATE INDEX admin_union_auth_sessions_pending_expiry_idx
  ON app.admin_union_auth_sessions (expires_at)
  WHERE status = 'pending';

CREATE INDEX admin_union_auth_sessions_account_idx
  ON app.admin_union_auth_sessions (app_id, union_account_id);

CREATE INDEX admin_union_auth_sessions_created_by_idx
  ON app.admin_union_auth_sessions (app_id, created_by);

GRANT SELECT, INSERT, UPDATE ON app.admin_union_auth_sessions TO couli_app;
GRANT SELECT (id, app_id, union_account_id, created_by, expires_at, used_at, status, error,
  created_at, finished_at, updated_at)
  ON app.admin_union_auth_sessions TO couli_readonly;
