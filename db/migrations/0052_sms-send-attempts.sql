-- SMS send attempts: the PG-authoritative per-IP hourly send count (规划/08 BR-ID-05 细则「发码与设备
-- 注册的风控默认值」sms.ip_sends_per_hour, BR-ID-32 landing page send; implementation rule written
-- back by couli #150). Task B1-11g round 7 (orchestrator ruling 2026-10-19).
-- Compatibility: additive. One new ordinary table in schema app with named constraints, one index
-- and grants; no existing object changes.
-- Recovery: restore from backup; no down migration.
--
-- One row per SMS send request that passed the per-IP admission, from both entries (the app route
-- POST /v1/auth/sms-codes and the landing page POST /v1/landing/sms-codes); written by risk only.
--   attempt_id: UUIDv7 generated by the server per request (both operations are x-idempotent:
--     false, a client retry is a new request and a new row). Key (app_id, attempt_id).
--   ip_hmac / phone_hmac: keyed blind indexes (lowercase hex) of the client IP and the normalised
--     phone; never the clear values.
--   status: pending when admitted (committed before the provider is called), then accepted /
--     failed / unknown from the send's outcome, written once through risk's transition table
--     (pending → accepted | failed | unknown; the three are final, never rewritten) by an UPDATE
--     conditioned on app_id and status = 'pending'. pending, accepted and unknown count towards
--     the IP's limit; failed (the provider definitely refused, or nothing was sent) does not. The
--     result update may fail and the row then stays pending (still counted).
--   created_at: the injected Clock at admission (no database default: the count window is measured
--     on it); updated_at: the Clock at the last status write.
-- Count: counted rows of (app_id, ip_hmac) with created_at in [now − 3600 s − send bound, now];
-- the row is inserted under a transaction-level advisory lock on (app_id, ip_hmac) after
-- counting, so the count never exceeds the limit. Rows are never deleted or rolled back by the application.
-- Retention: TODO(规划/11 §7.1): no purge job yet — blocked on a BR-ID-30 retention period for this
-- table (rows are kept; only the last hour is ever read).
--
-- Grants: couli_app SELECT, INSERT and UPDATE (status, updated_at) only; no DELETE, TRUNCATE,
-- REFERENCES or TRIGGER for anyone. couli_readonly SELECT.
--
-- Timeouts: a new empty table and its index; 5s lock wait so a blocked deploy fails fast, 30s
-- overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.sms_send_attempts (
  app_id      text        NOT NULL,
  attempt_id  uuid        NOT NULL,
  ip_hmac     text        NOT NULL,
  phone_hmac  text        NOT NULL,
  status      text        NOT NULL,
  created_at  timestamptz NOT NULL,
  updated_at  timestamptz NOT NULL,
  CONSTRAINT sms_send_attempts_pkey PRIMARY KEY (app_id, attempt_id),
  CONSTRAINT sms_send_attempts_ip_hmac_check CHECK (ip_hmac ~ '^[0-9a-f]{32,128}$'),
  CONSTRAINT sms_send_attempts_phone_hmac_check CHECK (phone_hmac ~ '^[0-9a-f]{32,128}$'),
  CONSTRAINT sms_send_attempts_status_check
    CHECK (status IN ('pending', 'accepted', 'failed', 'unknown')),
  CONSTRAINT sms_send_attempts_updated_check CHECK (updated_at >= created_at)
);

CREATE INDEX sms_send_attempts_ip_created_idx
  ON app.sms_send_attempts (app_id, ip_hmac, created_at);

GRANT SELECT, INSERT ON app.sms_send_attempts TO couli_app;
GRANT UPDATE (status, updated_at) ON app.sms_send_attempts TO couli_app;
GRANT SELECT ON app.sms_send_attempts TO couli_readonly;
