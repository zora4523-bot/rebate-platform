-- Up Migration
-- Account deletion requests (规划/04 §3.2 deletion_requests; 规划/08 BR-ID-27, BR-ID-28, where the
-- table is called account_deletions and apply_at is called requested_at; contracts/enums
-- identity.yaml deletion_status / deletion_cancel_reason). Task B1-15a (orchestrator ruling §9.2,
-- §9.3). Storage only: the state machine is B1-15b, the read port B1-15c, the endpoints and the
-- 30412 / 30416 guards B1-15d.
-- Compatibility: additive. One new ordinary table in schema app with named constraints, three
-- indexes and grants; no existing object changes (the foreign key only takes a SHARE ROW EXCLUSIVE
-- lock on users while it is added).
-- Recovery: restore from backup; no down migration.
--
-- app.deletion_requests: one row per deletion application. Writer: identity only (02 §4.1: apply,
-- user cancel, the cooling-expiry job and processing completion all live in identity); other
-- modules read through the port identity exports (B1-15c). Rows are never deleted; users rows are
-- tombstones and never deleted either, so the foreign key does not cascade.
--   id: UUIDv7 generated by the application (packages/domain); no column default.
--   user_id: the applicant (foreign key to users (app_id, id)).
--   status: cooling / processing / done / cancelled (deletion_status). No default: the
--     application writes 'cooling' explicitly on insert.
--   apply_at: when the application was accepted.
--   cooling_until: end of the cancellable window (apply_at + 7×24 hours, computed by the
--     application). The database only guards cooling_until > apply_at; the seven days live in
--     08 / the application, not here.
--   cancelled_at / cancel_reason: present exactly when status = 'cancelled'. cancel_reason is
--     user (explicit cancel, only strictly before cooling_until) or negative_balance (the expiry
--     re-check found available_fen < 0, so at or after cooling_until).
--   processed_at: when the request reached done (the 15-working-day limit is measured to done);
--     present exactly when status = 'done', never before cooling_until. Entry into processing is
--     traced by users.status = 'deleting' and this row's updated_at.
--   balance_snapshot_fen: available balance at application time (bigint fen, >= 0: a negative
--     balance cannot apply, 30416). Fixed at insert; the expiry re-check does not overwrite it.
--     04 writes balance_snapshot; the _fen suffix follows the 04 §3.2 money-column rule.
--   row_version: optimistic version, starts at 0.
-- No business instant has a SQL clock default: apply_at, cooling_until, cancelled_at and
-- processed_at come from the injected Clock. No cross-table constraint against users.status
-- (triggers do no business transitions).
--
-- Indexes: at most one open request (cooling or processing) per (app_id, user_id), enforced by a
-- partial unique index so concurrent applications yield one row and one 23505 (cancelled and done
-- history may repeat); (status, cooling_until) for the cross-app cooling-expiry job;
-- (app_id, user_id, apply_at DESC) for the latest request of a user.
--
-- Grants (one GRANT per role): couli_app SELECT, INSERT and column-level UPDATE on the lifecycle
-- columns only (identity, application time, cooling deadline, balance snapshot and created_at are
-- never updatable); no DELETE, TRUNCATE, REFERENCES or TRIGGER for anyone. couli_readonly SELECT.
--
-- Timeouts: one new empty table, one foreign key (SHARE ROW EXCLUSIVE lock on users while it is
-- added) and three indexes on an empty table; 5s lock wait so a blocked deploy fails fast, 30s
-- overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.deletion_requests (
  id                    uuid        NOT NULL,
  app_id                text        NOT NULL,
  user_id               uuid        NOT NULL,
  status                text        NOT NULL,
  apply_at              timestamptz NOT NULL,
  cooling_until         timestamptz NOT NULL,
  cancelled_at          timestamptz,
  cancel_reason         text,
  processed_at          timestamptz,
  balance_snapshot_fen  bigint      NOT NULL,
  row_version           integer     NOT NULL DEFAULT 0,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT deletion_requests_pkey PRIMARY KEY (id),
  CONSTRAINT deletion_requests_user_fkey FOREIGN KEY (app_id, user_id)
    REFERENCES app.users (app_id, id),
  CONSTRAINT deletion_requests_status_check
    CHECK (status IN ('cooling', 'processing', 'done', 'cancelled')),
  CONSTRAINT deletion_requests_cancel_reason_check
    CHECK (cancel_reason IN ('user', 'negative_balance')),
  CONSTRAINT deletion_requests_balance_snapshot_fen_check CHECK (balance_snapshot_fen >= 0),
  CONSTRAINT deletion_requests_cooling_window_check CHECK (cooling_until > apply_at),
  -- Boolean equality on IS NOT NULL: a null never slips through as it would with plain =.
  CONSTRAINT deletion_requests_cancel_reason_pair_check
    CHECK ((status = 'cancelled') = (cancel_reason IS NOT NULL)),
  CONSTRAINT deletion_requests_cancelled_at_pair_check
    CHECK ((status = 'cancelled') = (cancelled_at IS NOT NULL)),
  CONSTRAINT deletion_requests_done_pair_check
    CHECK ((status = 'done') = (processed_at IS NOT NULL)),
  -- BR-ID-27: a user cancel is decided by now < cooling_until; the negative-balance cancel is the
  -- expiry re-check, so it happens at or after cooling_until.
  CONSTRAINT deletion_requests_user_cancel_window_check
    CHECK (cancel_reason IS DISTINCT FROM 'user' OR cancelled_at < cooling_until),
  CONSTRAINT deletion_requests_negative_balance_window_check
    CHECK (cancel_reason IS DISTINCT FROM 'negative_balance' OR cancelled_at >= cooling_until),
  CONSTRAINT deletion_requests_processed_after_check
    CHECK (processed_at IS NULL OR processed_at >= cooling_until)
);

CREATE UNIQUE INDEX deletion_requests_open_user_key
  ON app.deletion_requests (app_id, user_id)
  WHERE status IN ('cooling', 'processing');

CREATE INDEX deletion_requests_status_cooling_until_idx
  ON app.deletion_requests (status, cooling_until);

CREATE INDEX deletion_requests_user_apply_idx
  ON app.deletion_requests (app_id, user_id, apply_at DESC);

GRANT SELECT, INSERT,
  UPDATE (status, cancelled_at, cancel_reason, processed_at, row_version, updated_at)
  ON app.deletion_requests TO couli_app;
GRANT SELECT ON app.deletion_requests TO couli_readonly;
