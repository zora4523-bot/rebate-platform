-- Up Migration
-- Yearly withholding ledger of withdrawals (08 BR-WDR-20 税额计算与年度台账; 规划/04 §3.2 tax_ytd;
-- orchestrator rulings D10-456 ④ and D10-459, 2026-10-31). Task B2-08a; the accumulation on
-- PAID_API / PAID_MANUAL is B2-08b, the tax calculation B2-08c, the quarterly export B2-08d.
-- Compatibility: additive. One new empty table, named constraints and indexes, grants.
-- Recovery: restore from backup; no down migration.
--
-- tax_ytd: one row per (app_id, user_id, year, income_type, identity_hmac). year is the tax year of
--   the withdrawal's created_at in +08:00 (BR-WDR-20: 12 月申请、次年 1 月到账的单记在申请那一年);
--   income_type is SERVICE_FEE for every commission withdrawal (SELF_REBATE is no longer used,
--   INCIDENTAL is P1: a later migration widens the CHECK); identity_hmac is the real-name id_no_hmac
--   of the member at accumulation time (the identity dimension of BR-ID-25 细则「实名更正」: after a
--   correction the new identity starts its own row, the old one stops accumulating; same shape as
--   realname_prior_identities.id_no_hmac, never a name or an ID number in plaintext).
--   cum_income_fen adds the withdrawal's amount_fen and cum_withheld_fen its tax_fen when the
--   withdrawal becomes PAID_API / PAID_MANUAL (W5 / W8 / W10 / W11); rejected and failed
--   withdrawals never accumulate. continuous_months is reserved for the cumulative method
--   (BR-WDR-20, 0 until B2-08c uses it). The row's identity (app_id, user_id, year, income_type,
--   identity_hmac), id and created_at never change; an accumulation is an upsert on
--   tax_ytd_identity_key that rewrites the three counters and updated_at. id is generated by the
--   application. Amounts are integer fen (bigint, ≥ 0).
-- Writer: the payout module (couli_app: the worker's landing and the admin entry's write-off).
-- Retention: none here (the archive of BR-ID-29 is identity's, not this table).
--
-- Grants: couli_app SELECT, INSERT and column UPDATE of the three counters and updated_at (no
-- DELETE / TRUNCATE); couli_payout SELECT; couli_readonly SELECT. couli_maint gets nothing.
--
-- Timeouts: only a new, empty table and its indexes are created; short catalog locks only. 5s lock
-- wait so a blocked deploy fails fast, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.tax_ytd (
  id                uuid NOT NULL,
  app_id            text NOT NULL,
  user_id           uuid NOT NULL,
  year              integer NOT NULL,
  income_type       text NOT NULL,
  identity_hmac     text NOT NULL,
  cum_income_fen    bigint NOT NULL DEFAULT 0,
  cum_withheld_fen  bigint NOT NULL DEFAULT 0,
  continuous_months integer NOT NULL DEFAULT 0,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tax_ytd_pkey PRIMARY KEY (id),
  CONSTRAINT tax_ytd_identity_key UNIQUE (app_id, user_id, year, income_type, identity_hmac),
  CONSTRAINT tax_ytd_user_fkey FOREIGN KEY (app_id, user_id) REFERENCES app.users (app_id, id),
  CONSTRAINT tax_ytd_app_id_check CHECK (app_id <> ''),
  CONSTRAINT tax_ytd_year_check CHECK (year BETWEEN 2026 AND 2100),
  CONSTRAINT tax_ytd_income_type_check CHECK (income_type IN ('SERVICE_FEE')),
  CONSTRAINT tax_ytd_identity_hmac_check CHECK (identity_hmac ~ '^[0-9a-f]{64}$'),
  CONSTRAINT tax_ytd_cum_income_fen_check CHECK (cum_income_fen >= 0),
  CONSTRAINT tax_ytd_cum_withheld_fen_check CHECK (cum_withheld_fen >= 0),
  CONSTRAINT tax_ytd_continuous_months_check CHECK (continuous_months >= 0)
);

CREATE INDEX tax_ytd_user_year_idx ON app.tax_ytd (app_id, user_id, year);

GRANT SELECT, INSERT ON app.tax_ytd TO couli_app;
GRANT UPDATE (cum_income_fen, cum_withheld_fen, continuous_months, updated_at)
  ON app.tax_ytd TO couli_app;
GRANT SELECT ON app.tax_ytd TO couli_payout;
GRANT SELECT ON app.tax_ytd TO couli_readonly;
