-- Up Migration
-- Second order-table migration (规划/04 §3.2 order_sync_requests, rights_imports /
-- rights_import_failures; 01 F-ORD-10, 04 §6.6 order-syncs / rights-imports; 08 BR-FUND-06 细则
-- 「维权导入任务」; orchestrator J-8 order_assignments; ruling D10-169 K-2 order_rights key).
-- Task B1-09e. Storage only: the orders writers and the settlement import command are later tasks.
-- Compatibility: additive. Four new empty tables with named constraints / indexes, two append-only
-- guard triggers, grants, and one new unique index on the existing app.order_rights (no column,
-- constraint, data or grant change there).
-- Recovery: restore from backup; no down migration. If the order_rights index build fails on
-- duplicate rows (none before launch), the whole migration rolls back; the duplicates have to be
-- resolved by a settlement data-fix task before re-running.
--
-- Common: every table has app_id text NOT NULL; foreign keys carry app_id (no cross-app rows), are
-- named and never cascade. ids are uuid generated by the application (no default). Business times
-- have no database default; created_at defaults to now() only as the technical insert time.
-- Enumerations follow contracts/enums/order.yaml (CT-24n) and are CHECKs; platform follows
-- contracts/enums/platform.yaml. "from" / "to" keep the 04 §3.2 column names and are quoted.
--
-- order_sync_requests: manual order sync of the admin console. mode window carries from < to
--   (to exclusive) and an optional status_filter, never order_nos; mode order_nos carries 1–50
--   sub-order numbers and no window. filter_digest is the sha256 hex digest of the normalised
--   filter (platform, mode, window or order numbers, status_filter) computed by the orders module;
--   order_sync_requests_live_digest_key makes it unique per app while the request is queued or
--   running, so an equal request submitted meanwhile is decided by PostgreSQL and the handler
--   returns the existing one (contract: reused=true); done / failed requests release it.
--   finished_at is set exactly when the request has ended (done / failed). requested_by is the
--   admin from the token.
-- rights_imports: one row per uploaded Excel (kind rights / punish / channel). No uniqueness on
--   file_path: uploading the same file again creates a new task (BR-FUND-06), already imported
--   rows are skipped by the order_rights key below and counted in duplicate_rows, separately
--   from skipped_rows (outside the time window) and failed_rows. time_basis and the from / to
--   window are set together or all empty; a channel import (kind channel) requires
--   union_account_id and has no time window. finished_at as for order_sync_requests.
-- rights_import_failures: per-row failures of an import, insert-only, one row per
--   (import_id, row_no); reason is the rights_import_failure_reason enum.
-- order_assignments: manual order assignment / claim log (J-8), insert-only. order_id references
--   order_keys (not the partitioned orders table); an admin assignment records the admin, a claim
--   may leave admin_id empty.
-- order_rights_dedupe_key (K-2, BR-FUND-06 去重键): at most one rights row per
--   (app_id, order_id, type, platform_rights_no), NULLS NOT DISTINCT so rows without a platform
--   rights number also deduplicate. The table belongs to settlement; only the index is added here.
-- Retention: none here.
--
-- Grants: couli_app SELECT, INSERT on the four tables; UPDATE only on the progress columns of
-- order_sync_requests (status, tallies, error, finished_at) and rights_imports (status, tallies,
-- finished_at); no UPDATE / DELETE on the two insert-only tables, whose app.reject_update_delete()
-- triggers (0003) reject UPDATE and DELETE for every role as a second line of defence.
-- couli_readonly SELECT. couli_payout and couli_maint get nothing. order_rights grants unchanged.
--
-- Timeouts: new empty tables plus one index build on app.order_rights, which takes a SHARE lock
-- on it (small before launch). 5s lock wait so a blocked deploy fails fast instead of queueing
-- settlement writes behind it, 60s overall as a ceiling for the index build.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE app.order_sync_requests (
  id            uuid NOT NULL,
  app_id        text NOT NULL,
  platform      text NOT NULL,
  mode          text NOT NULL,
  "from"        timestamptz,
  "to"          timestamptz,
  status_filter text,
  order_nos     text[],
  filter_digest text NOT NULL,
  status        text NOT NULL,
  requested_by  uuid NOT NULL,
  fetched_count integer NOT NULL DEFAULT 0,
  stored_count  integer NOT NULL DEFAULT 0,
  error         text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  finished_at   timestamptz,
  CONSTRAINT order_sync_requests_pkey PRIMARY KEY (id),
  CONSTRAINT order_sync_requests_requested_by_fkey FOREIGN KEY (app_id, requested_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT order_sync_requests_platform_check CHECK (platform IN ('taobao', 'jd', 'pdd',
    'meituan', 'vip', 'douyin', 'eleme', 'kuaishou', 'suning')),
  CONSTRAINT order_sync_requests_mode_check CHECK (mode IN ('window', 'order_nos')),
  CONSTRAINT order_sync_requests_status_check
    CHECK (status IN ('queued', 'running', 'done', 'failed')),
  CONSTRAINT order_sync_requests_window_check CHECK (
    mode <> 'window'
    OR ("from" IS NOT NULL AND "to" IS NOT NULL AND "from" < "to" AND order_nos IS NULL)
  ),
  CONSTRAINT order_sync_requests_order_nos_check CHECK (
    mode <> 'order_nos'
    OR (order_nos IS NOT NULL AND array_ndims(order_nos) = 1
      AND cardinality(order_nos) BETWEEN 1 AND 50
      AND "from" IS NULL AND "to" IS NULL AND status_filter IS NULL)
  ),
  CONSTRAINT order_sync_requests_status_filter_check
    CHECK (status_filter IS NULL OR length(status_filter) BETWEEN 1 AND 64),
  CONSTRAINT order_sync_requests_filter_digest_check CHECK (filter_digest ~ '^[0-9a-f]{64}$'),
  CONSTRAINT order_sync_requests_counts_check CHECK (fetched_count >= 0 AND stored_count >= 0),
  CONSTRAINT order_sync_requests_finished_check
    CHECK ((status IN ('done', 'failed')) = (finished_at IS NOT NULL))
);

CREATE UNIQUE INDEX order_sync_requests_live_digest_key
  ON app.order_sync_requests (app_id, filter_digest)
  WHERE status IN ('queued', 'running');

CREATE INDEX order_sync_requests_created_idx
  ON app.order_sync_requests (app_id, created_at);

CREATE TABLE app.rights_imports (
  id               uuid NOT NULL,
  app_id           text NOT NULL,
  kind             text NOT NULL,
  platform         text NOT NULL,
  union_account_id uuid,
  time_basis       text,
  "from"           timestamptz,
  "to"             timestamptz,
  file_path        text NOT NULL,
  status           text NOT NULL,
  total_rows       integer NOT NULL DEFAULT 0,
  succeeded_rows   integer NOT NULL DEFAULT 0,
  failed_rows      integer NOT NULL DEFAULT 0,
  skipped_rows     integer NOT NULL DEFAULT 0,
  duplicate_rows   integer NOT NULL DEFAULT 0,
  created_by       uuid NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  finished_at      timestamptz,
  CONSTRAINT rights_imports_pkey PRIMARY KEY (id),
  CONSTRAINT rights_imports_app_id_id_key UNIQUE (app_id, id),
  CONSTRAINT rights_imports_union_account_fkey FOREIGN KEY (app_id, union_account_id)
    REFERENCES app.union_accounts (app_id, id),
  CONSTRAINT rights_imports_created_by_fkey FOREIGN KEY (app_id, created_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT rights_imports_kind_check CHECK (kind IN ('rights', 'punish', 'channel')),
  CONSTRAINT rights_imports_platform_check CHECK (platform IN ('taobao', 'jd', 'pdd', 'meituan',
    'vip', 'douyin', 'eleme', 'kuaishou', 'suning')),
  CONSTRAINT rights_imports_time_basis_check
    CHECK (time_basis IS NULL OR time_basis IN ('paid', 'received')),
  CONSTRAINT rights_imports_status_check
    CHECK (status IN ('queued', 'running', 'done', 'failed')),
  CONSTRAINT rights_imports_window_check CHECK (
    (time_basis IS NULL AND "from" IS NULL AND "to" IS NULL)
    OR (time_basis IS NOT NULL AND "from" IS NOT NULL AND "to" IS NOT NULL AND "from" < "to")
  ),
  CONSTRAINT rights_imports_channel_check CHECK (
    kind <> 'channel'
    OR (union_account_id IS NOT NULL AND time_basis IS NULL AND "from" IS NULL AND "to" IS NULL)
  ),
  CONSTRAINT rights_imports_file_path_check CHECK (file_path <> ''),
  CONSTRAINT rights_imports_counts_check CHECK (total_rows >= 0 AND succeeded_rows >= 0
    AND failed_rows >= 0 AND skipped_rows >= 0 AND duplicate_rows >= 0),
  CONSTRAINT rights_imports_finished_check
    CHECK ((status IN ('done', 'failed')) = (finished_at IS NOT NULL))
);

CREATE INDEX rights_imports_created_idx ON app.rights_imports (app_id, created_at);

CREATE TABLE app.rights_import_failures (
  app_id     text NOT NULL,
  import_id  uuid NOT NULL,
  row_no     integer NOT NULL,
  reason     text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT rights_import_failures_pkey PRIMARY KEY (import_id, row_no),
  CONSTRAINT rights_import_failures_import_fkey FOREIGN KEY (app_id, import_id)
    REFERENCES app.rights_imports (app_id, id),
  CONSTRAINT rights_import_failures_row_no_check CHECK (row_no > 0),
  CONSTRAINT rights_import_failures_reason_check CHECK (reason IN ('invalid_row',
    'order_not_found', 'sub_order_no_missing', 'received_at_missing', 'platform_mismatch'))
);

CREATE TRIGGER rights_import_failures_append_only
  BEFORE UPDATE OR DELETE ON app.rights_import_failures
  FOR EACH ROW EXECUTE FUNCTION app.reject_update_delete();

CREATE TABLE app.order_assignments (
  id         uuid NOT NULL,
  app_id     text NOT NULL,
  order_id   uuid NOT NULL,
  to_user_id uuid NOT NULL,
  source     text NOT NULL,
  reason     text,
  admin_id   uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT order_assignments_pkey PRIMARY KEY (id),
  CONSTRAINT order_assignments_order_fkey FOREIGN KEY (app_id, order_id)
    REFERENCES app.order_keys (app_id, order_id),
  CONSTRAINT order_assignments_to_user_fkey FOREIGN KEY (app_id, to_user_id)
    REFERENCES app.users (app_id, id),
  CONSTRAINT order_assignments_admin_fkey FOREIGN KEY (app_id, admin_id)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT order_assignments_source_check CHECK (source IN ('claim', 'admin')),
  CONSTRAINT order_assignments_admin_id_check CHECK (source <> 'admin' OR admin_id IS NOT NULL)
);

CREATE INDEX order_assignments_order_idx ON app.order_assignments (app_id, order_id);
CREATE INDEX order_assignments_to_user_idx ON app.order_assignments (app_id, to_user_id);

CREATE TRIGGER order_assignments_append_only
  BEFORE UPDATE OR DELETE ON app.order_assignments
  FOR EACH ROW EXECUTE FUNCTION app.reject_update_delete();

CREATE UNIQUE INDEX order_rights_dedupe_key
  ON app.order_rights (app_id, order_id, type, platform_rights_no) NULLS NOT DISTINCT;

