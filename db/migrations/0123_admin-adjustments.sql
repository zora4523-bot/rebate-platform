-- Up Migration
-- admin_adjustments and bad_debt_writeoffs: the manual adjustment form and the negative-balance
-- write-off candidate (规划/04 §3.2 admin_adjustments, bad_debt_writeoffs; 08 BR-FUND-24, BR-FUND-12,
-- BR-FUND-16; orchestrator rulings D10-534, D10-587, D10-590). Task B2-12a; the writers and readers
-- come in a later task. The status columns follow specs/state-machines/admin-adjustment.yaml and
-- specs/state-machines/bad-debt-writeoff.yaml; status values come from contracts/enums/fund.yaml.
-- Compatibility: additive. Two new empty tables with named constraints and indexes, and grants; no
-- existing object changes, no backfill (the foreign keys take SHARE ROW EXCLUSIVE locks on users,
-- admin_users, ledger_accounts and ledger_vouchers while they are added).
-- Recovery: restore from backup; no down migration.
--
-- admin_adjustments: adjust_id is the primary key and the {adjust_id} of the voucher keys
--   ADJ:{adjust_id} and ADJ:{adjust_id}:REVERSE; it is generated by the application (no SQL
--   default).
--   - A form a person files is submitted and approved in one step (status APPROVED at insert); only a
--     form the system prefills for a deletion (ACCOUNT_CLOSED, created_by null, amount_fen null until
--     approval, BR-FUND-24 ⑧) is inserted PENDING and later approved (amount, voucher and reviewer
--     are filled in then) or rejected (reject_note required). CANCELLED stays in the CHECK as the
--     contract lists it, but no transition writes it (D10-590 ⑨).
--   - refs is a jsonb array of {ref_type, ref_id} (at most 10). It is empty only on an OTHER form
--     whose note stands in for a document and on a reversal, whose link is reverses_adjust_id
--     (BR-FUND-24 ③). The element shape is checked by the service against the contract.
--   - A form is reversed at most once (partial unique key on reverses_adjust_id; the voucher key
--     ADJ:{adjust_id}:REVERSE backs it up). reversed_by_adjust_id is not a column: it is derived by a
--     self join. That a reversal points at an APPROVED, not-yet-reversed, non-reversal form with the
--     opposite direction and the same amount is checked by the service under the row lock.
--   - At most one PENDING ACCOUNT_CLOSED form per member (partial unique key), so the daily round
--     can rebuild one after a rejection without making duplicates (D10-590).
--   - contra_platform names the platform only for UNION_RECEIVABLE.
-- bad_debt_writeoffs: id is the primary key and the {candidate_id} of BADDEBT:{account_id}:{id};
--   generated by the application. At most one PENDING candidate per account (BR-FUND-12). user_id,
--   available_fen, frozen_fen, negative_days and approve_blocked are derived when read (contract
--   AdminBadDebtWriteoff), never stored. A refused approval (frozen money, switch on) leaves the row
--   PENDING; APPROVED carries the BAD_DEBT_WRITEOFF voucher, CANCELLED never has one.
-- Writers: ledger / admin (couli_app). Rows are never deleted.
--
-- Grants: couli_app SELECT, INSERT and column UPDATE of the decision columns and row_version only
-- (no DELETE / TRUNCATE; identity and filing columns are not updatable); couli_readonly SELECT. No
-- other role gets any privilege.
--
-- Timeouts: only new, empty tables and their indexes are created; short catalog locks only. 5s lock
-- wait so a blocked deploy fails fast, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.admin_adjustments (
  adjust_id          uuid NOT NULL,
  app_id             text NOT NULL,
  user_id            uuid NOT NULL,
  direction          text NOT NULL,
  amount_fen         bigint,
  reason_code        text NOT NULL,
  refs               jsonb NOT NULL,
  contra_subject     text NOT NULL,
  contra_platform    text,
  note               text,
  status             text NOT NULL,
  reverses_adjust_id uuid,
  created_by         uuid,
  created_at         timestamptz NOT NULL DEFAULT now(),
  reviewed_by        uuid,
  reviewed_at        timestamptz,
  reject_note        text,
  voucher_id         uuid,
  row_version        integer NOT NULL DEFAULT 0,
  CONSTRAINT admin_adjustments_pkey PRIMARY KEY (adjust_id),
  CONSTRAINT admin_adjustments_app_id_adjust_id_key UNIQUE (app_id, adjust_id),
  CONSTRAINT admin_adjustments_user_fkey FOREIGN KEY (app_id, user_id)
    REFERENCES app.users (app_id, id),
  CONSTRAINT admin_adjustments_created_by_fkey FOREIGN KEY (app_id, created_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT admin_adjustments_reviewed_by_fkey FOREIGN KEY (app_id, reviewed_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT admin_adjustments_voucher_fkey FOREIGN KEY (app_id, voucher_id)
    REFERENCES app.ledger_vouchers (app_id, id),
  CONSTRAINT admin_adjustments_reverses_fkey FOREIGN KEY (app_id, reverses_adjust_id)
    REFERENCES app.admin_adjustments (app_id, adjust_id),
  CONSTRAINT admin_adjustments_app_id_check CHECK (app_id <> ''),
  CONSTRAINT admin_adjustments_direction_check CHECK (direction IN ('increase', 'decrease')),
  CONSTRAINT admin_adjustments_amount_fen_check CHECK (amount_fen IS NULL OR amount_fen > 0),
  CONSTRAINT admin_adjustments_amount_required_check CHECK (
    amount_fen IS NOT NULL OR reason_code = 'ACCOUNT_CLOSED'
  ),
  CONSTRAINT admin_adjustments_reason_code_check CHECK (
    reason_code IN ('RESTORE', 'RECON_FIX', 'PAYOUT_RECOVERY', 'ACCOUNT_CLOSED', 'OTHER')
  ),
  -- CASE, not AND / OR: PostgreSQL does not promise left-to-right evaluation, and
  -- jsonb_array_length raises on a non-array.
  CONSTRAINT admin_adjustments_refs_check CHECK (
    CASE WHEN jsonb_typeof(refs) = 'array' THEN jsonb_array_length(refs) <= 10 ELSE false END
  ),
  CONSTRAINT admin_adjustments_refs_required_check CHECK (
    reason_code = 'OTHER'
    OR reverses_adjust_id IS NOT NULL
    OR CASE WHEN jsonb_typeof(refs) = 'array' THEN jsonb_array_length(refs) >= 1 ELSE true END
  ),
  CONSTRAINT admin_adjustments_reversal_refs_check CHECK (
    reverses_adjust_id IS NULL OR refs = '[]'::jsonb
  ),
  CONSTRAINT admin_adjustments_reverses_self_check CHECK (reverses_adjust_id <> adjust_id),
  CONSTRAINT admin_adjustments_contra_subject_check CHECK (
    contra_subject IN (
      'COMMISSION_REVENUE', 'UNION_RECEIVABLE', 'BAD_DEBT', 'MKT_EXPENSE',
      'CASH_ALIPAY', 'CASH_WECHAT', 'CASH_BANK'
    )
  ),
  CONSTRAINT admin_adjustments_contra_platform_check CHECK (
    (contra_subject = 'UNION_RECEIVABLE') = (contra_platform IS NOT NULL)
  ),
  CONSTRAINT admin_adjustments_contra_platform_value_check CHECK (
    contra_platform IN ('taobao', 'jd', 'pdd', 'meituan', 'vip', 'douyin', 'eleme', 'kuaishou', 'suning')
  ),
  CONSTRAINT admin_adjustments_note_check CHECK (char_length(note) <= 500),
  CONSTRAINT admin_adjustments_status_check CHECK (
    status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')
  ),
  CONSTRAINT admin_adjustments_created_by_check CHECK (
    created_by IS NOT NULL OR reason_code = 'ACCOUNT_CLOSED'
  ),
  CONSTRAINT admin_adjustments_approved_check CHECK (
    status <> 'APPROVED'
    OR (
      amount_fen IS NOT NULL AND voucher_id IS NOT NULL
      AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL
    )
  ),
  CONSTRAINT admin_adjustments_voucher_check CHECK (status = 'APPROVED' OR voucher_id IS NULL),
  CONSTRAINT admin_adjustments_rejected_check CHECK (
    status <> 'REJECTED' OR (reject_note IS NOT NULL AND btrim(reject_note) <> '')
  ),
  CONSTRAINT admin_adjustments_reject_note_check CHECK (char_length(reject_note) <= 200),
  CONSTRAINT admin_adjustments_row_version_check CHECK (row_version >= 0)
);

-- A form is reversed at most once (BR-FUND-24 细则「红冲只按原单整笔」).
CREATE UNIQUE INDEX admin_adjustments_reverses_key
  ON app.admin_adjustments (app_id, reverses_adjust_id)
  WHERE reverses_adjust_id IS NOT NULL;
-- At most one PENDING prefilled ACCOUNT_CLOSED form per member (BR-FUND-24 ⑧, D10-590).
CREATE UNIQUE INDEX admin_adjustments_account_closed_pending_key
  ON app.admin_adjustments (app_id, user_id)
  WHERE reason_code = 'ACCOUNT_CLOSED' AND status = 'PENDING';
-- adminListAdjustments: created_at, then adjust_id, both descending; status and user filters.
CREATE INDEX admin_adjustments_list_idx
  ON app.admin_adjustments (app_id, created_at DESC, adjust_id DESC);
CREATE INDEX admin_adjustments_status_idx
  ON app.admin_adjustments (app_id, status);
CREATE INDEX admin_adjustments_user_idx
  ON app.admin_adjustments (app_id, user_id);

GRANT SELECT, INSERT ON app.admin_adjustments TO couli_app;
GRANT UPDATE (amount_fen, status, reviewed_by, reviewed_at, reject_note, voucher_id, row_version)
  ON app.admin_adjustments TO couli_app;
GRANT SELECT ON app.admin_adjustments TO couli_readonly;

CREATE TABLE app.bad_debt_writeoffs (
  id             uuid NOT NULL,
  app_id         text NOT NULL,
  account_id     uuid NOT NULL,
  negative_since date NOT NULL,
  candidate_fen  bigint NOT NULL,
  status         text NOT NULL,
  initiator_id   uuid,
  approver_id    uuid,
  approved_at    timestamptz,
  voucher_id     uuid,
  created_at     timestamptz NOT NULL DEFAULT now(),
  row_version    integer NOT NULL DEFAULT 0,
  CONSTRAINT bad_debt_writeoffs_pkey PRIMARY KEY (id),
  CONSTRAINT bad_debt_writeoffs_app_id_id_key UNIQUE (app_id, id),
  CONSTRAINT bad_debt_writeoffs_account_fkey FOREIGN KEY (app_id, account_id)
    REFERENCES app.ledger_accounts (app_id, id),
  CONSTRAINT bad_debt_writeoffs_initiator_fkey FOREIGN KEY (app_id, initiator_id)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT bad_debt_writeoffs_approver_fkey FOREIGN KEY (app_id, approver_id)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT bad_debt_writeoffs_voucher_fkey FOREIGN KEY (app_id, voucher_id)
    REFERENCES app.ledger_vouchers (app_id, id),
  CONSTRAINT bad_debt_writeoffs_app_id_check CHECK (app_id <> ''),
  CONSTRAINT bad_debt_writeoffs_status_check CHECK (status IN ('PENDING', 'APPROVED', 'CANCELLED')),
  CONSTRAINT bad_debt_writeoffs_approved_check CHECK (
    status <> 'APPROVED'
    OR (voucher_id IS NOT NULL AND approver_id IS NOT NULL AND approved_at IS NOT NULL)
  ),
  CONSTRAINT bad_debt_writeoffs_voucher_check CHECK (status = 'APPROVED' OR voucher_id IS NULL),
  CONSTRAINT bad_debt_writeoffs_row_version_check CHECK (row_version >= 0)
);

-- At most one PENDING candidate per account (BR-FUND-12).
CREATE UNIQUE INDEX bad_debt_writeoffs_account_pending_key
  ON app.bad_debt_writeoffs (app_id, account_id)
  WHERE status = 'PENDING';
-- adminListBadDebtWriteoffs: created_at, then id, both descending; status filter.
CREATE INDEX bad_debt_writeoffs_list_idx
  ON app.bad_debt_writeoffs (app_id, created_at DESC, id DESC);
CREATE INDEX bad_debt_writeoffs_status_idx
  ON app.bad_debt_writeoffs (app_id, status);
CREATE INDEX bad_debt_writeoffs_account_idx
  ON app.bad_debt_writeoffs (app_id, account_id);

GRANT SELECT, INSERT ON app.bad_debt_writeoffs TO couli_app;
GRANT UPDATE (status, approver_id, approved_at, voucher_id, row_version)
  ON app.bad_debt_writeoffs TO couli_app;
GRANT SELECT ON app.bad_debt_writeoffs TO couli_readonly;
