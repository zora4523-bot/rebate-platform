-- The appeal console writes (CT-24r adminRegisterAppeal / adminClaimAppeal / adminResolveAppeal;
-- 规划/08 BR-ID-36 细则「被拦截请求申诉」; 04 §3.2 appeals 来源 / 登记人 / 认领; 编排裁定 D10-158).
-- Task B1-03ze (task brief §9.4). Storage only: risk's appeal service (the single writer of
-- app.appeals and app.appeal_claims) writes them, the console detail reads them.
-- Compatibility: additive. On app.appeals one NOT NULL column with a constant default (catalog-only
-- on PG ≥ 11, no rewrite: every existing row reads source = app, which is what it is) and one
-- nullable column without default (catalog-only), two new CHECKs; one new, empty table. Nothing is
-- dropped, renamed or retyped, and no UPDATE grant is widened.
--   appeals.source  text NOT NULL DEFAULT 'app'. Who filed the appeal: app (the person in the app,
--     POST /v1/me/appeals) or admin (customer service, POST /admin/v1/appeals; contracts/enums
--     appeal_source). Written once at insert, never updated.
--   appeals.registered_by  text NULL. The admin_users.id of the registrant of an admin appeal (text
--     like handler_id); NULL for an app appeal. Written once at insert, never updated.
--   appeals_source_check  source is app or admin.
--   appeals_registered_by_check  an admin appeal names its registrant, an app appeal none.
--   Both CHECKs are added NOT VALID (new rows and updates are checked at once): appeals is a funds /
--   attribution table (tools/ci/lint-migrations.ts) and takes no squawk exception, so the
--   validation is the next migration (precedent 0079 / 0080). Every existing row is source app with
--   NULL registered_by, so none can violate them.
--   appeal_claims: one row per claim (POST …/claim), insert-only. A claim sets appeals.handler_id
--     to the caller and raises appeals.row_version by 1 (the compare-and-set); the row here records
--     that version (row_version = the appeal's row_version after the claim), the claimant and the
--     claim time. The appeal's current claim time (AdminAppealDetail.claimed_at) is the claimed_at of
--     the row whose row_version equals the appeal's current row_version: any later write of the
--     appeal (another claim, the resolution) raises the version, so a resolved appeal reads NULL
--     and a claim is never updated or deleted. This keeps the UPDATE grants of app.appeals as they
--     are (0014, 0079: status, handler_id, closed_at, row_version, updated_at only). id is
--     generated by the application (UUIDv7). appeal_claims_appeal_version_key makes one claim per
--     appeal version (a second guard behind the compare-and-set) and serves the lookup.
-- Writer: risk (couli_app, the admin entry). Retention: none here (an appeal is kept, so are its
-- claims). No personal data: ids and instants only.
-- Grants: couli_app SELECT, INSERT on appeal_claims (no UPDATE / DELETE / TRUNCATE: insert-only);
-- couli_readonly SELECT. The new appeals columns are covered by the table-level grants (couli_app
-- SELECT / INSERT, couli_readonly SELECT) and get no UPDATE. couli_payout and couli_maint get
-- nothing.
-- Recovery: restore from backup; no down migration. (Undoing it would be a later migration that,
-- once nothing reads or writes them, drops the table, the constraints and the two columns.)
--
-- Timeouts: ADD COLUMN (constant default or none) and ADD CONSTRAINT … NOT VALID are catalog-only
-- but take ACCESS EXCLUSIVE on app.appeals, and the new table's foreign key a SHARE ROW EXCLUSIVE
-- lock on it, held to commit (the runner uses one transaction); 5s lock wait so a blocked deploy
-- fails fast instead of queueing requests behind it, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

ALTER TABLE app.appeals ADD COLUMN source text DEFAULT 'app' NOT NULL;

ALTER TABLE app.appeals ADD COLUMN registered_by text;

ALTER TABLE app.appeals ADD CONSTRAINT appeals_source_check
  CHECK (source IN ('app', 'admin')) NOT VALID;

ALTER TABLE app.appeals ADD CONSTRAINT appeals_registered_by_check
  CHECK ((source = 'admin') = (registered_by IS NOT NULL)) NOT VALID;

CREATE TABLE app.appeal_claims (
  id uuid NOT NULL,
  app_id text NOT NULL,
  appeal_id uuid NOT NULL,
  row_version integer NOT NULL,
  handler_id text NOT NULL,
  claimed_at timestamptz NOT NULL,
  created_at timestamptz DEFAULT now() NOT NULL,
  CONSTRAINT appeal_claims_pkey PRIMARY KEY (id),
  CONSTRAINT appeal_claims_appeal_version_key UNIQUE (appeal_id, row_version),
  CONSTRAINT appeal_claims_appeal_fkey FOREIGN KEY (appeal_id) REFERENCES app.appeals (id),
  CONSTRAINT appeal_claims_row_version_check CHECK (row_version >= 1)
);

GRANT SELECT, INSERT ON app.appeal_claims TO couli_app;
GRANT SELECT ON app.appeal_claims TO couli_readonly;
