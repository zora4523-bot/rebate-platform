-- Up Migration
-- R2 payout channel reconciliation storage (08 BR-WDR-23 通道对账对提现的影响; 规划/04 §3.2 recon_channel,
-- payout_recon_runs; orchestrator ruling D10-408, 2026-10-29). Task B2-07a; the reconciliation itself is
-- B2-07b onwards.
-- Compatibility: additive. Two new empty tables, named constraints and indexes, grants.
-- Recovery: restore from backup; no down migration.
--
-- recon_channel: one row per reconciled payout of a T+1 run of the Alipay daily bill: 04's columns
--   (date, out_biz_no, channel_order_id, our_status, channel_status, our_amount_fen,
--   channel_amount_fen, result) plus app_id (multi-tenant) and bill_date. date is the +08:00 day the
--   run reconciles (@couli/domain); bill_date is the Alipay bill the row was read from (a PAID_*
--   near the day boundary is also looked up in the next day's bill). Interface payouts are keyed by
--   out_biz_no, manual successful payouts by the Alipay channel_order_id; each key is a partial
--   unique index per (app_id, bill_date). Either side may be missing: our_status / our_amount_fen
--   are NULL when the bill has a success with no withdrawal, channel_order_id / channel_status /
--   channel_amount_fen are NULL when a PAID_* has no bill record. our_status snapshots
--   withdrawals.status (BR-WDR-08); our_amount_fen is the withdrawal's net_fen, channel_amount_fen
--   the bill amount, both integer fen. result is the BR-WDR-23 outcome: matched, paying_query (①),
--   paying_manual (②), diff (③; the error ticket itself lives in recon_diffs). A rerun of the same
--   bill day rewrites the status, amount and result columns of its rows. id is generated by the
--   application.
-- payout_recon_runs: one row per (app_id, channel, bill_date) daily run; a rerun of the day
--   overwrites it (ON CONFLICT on payout_recon_runs_day_key). status succeeded / partial / failed;
--   the consecutive succeeded days gate BR-WDR-30 (D10-408). started_at / finished_at come from the
--   injected clock (no SQL clock default, db/AGENTS.md rule 6). channel is alipay only for R2; the
--   CHECK is extended by a later migration when another channel opens. id is generated by the
--   application.
-- Writer of both: the payout module (worker, couli_app).
-- Retention: none here.
--
-- Grants: couli_app SELECT, INSERT and column UPDATE of the columns a rerun rewrites (no DELETE /
-- TRUNCATE); couli_payout SELECT; couli_readonly SELECT. couli_maint gets nothing.
--
-- Timeouts: only new, empty tables and their indexes are created; short catalog locks only. 5s lock
-- wait so a blocked deploy fails fast, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.recon_channel (
  id                 uuid NOT NULL,
  app_id             text NOT NULL,
  date               date NOT NULL,
  bill_date          date NOT NULL,
  out_biz_no         text,
  channel_order_id   text,
  our_status         text,
  channel_status     text,
  our_amount_fen     bigint,
  channel_amount_fen bigint,
  result             text NOT NULL,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recon_channel_pkey PRIMARY KEY (id),
  CONSTRAINT recon_channel_app_id_check CHECK (app_id <> ''),
  CONSTRAINT recon_channel_key_check CHECK (out_biz_no IS NOT NULL OR channel_order_id IS NOT NULL),
  CONSTRAINT recon_channel_out_biz_no_check CHECK (out_biz_no <> ''),
  CONSTRAINT recon_channel_channel_order_id_check CHECK (channel_order_id <> ''),
  CONSTRAINT recon_channel_our_status_check CHECK (
    our_status IN (
      'PENDING_REVIEW', 'APPROVED', 'PAYING', 'REJECTED', 'PAID_API', 'PAID_MANUAL', 'FAILED'
    )
  ),
  CONSTRAINT recon_channel_channel_status_check CHECK (channel_status <> ''),
  CONSTRAINT recon_channel_our_amount_fen_check CHECK (our_amount_fen >= 0),
  CONSTRAINT recon_channel_channel_amount_fen_check CHECK (channel_amount_fen >= 0),
  CONSTRAINT recon_channel_result_check CHECK (
    result IN ('matched', 'paying_query', 'paying_manual', 'diff')
  )
);

CREATE UNIQUE INDEX recon_channel_out_biz_no_key
  ON app.recon_channel (app_id, bill_date, out_biz_no)
  WHERE out_biz_no IS NOT NULL;

CREATE UNIQUE INDEX recon_channel_channel_order_id_key
  ON app.recon_channel (app_id, bill_date, channel_order_id)
  WHERE channel_order_id IS NOT NULL;

CREATE TABLE app.payout_recon_runs (
  id          uuid NOT NULL,
  app_id      text NOT NULL,
  channel     text NOT NULL,
  bill_date   date NOT NULL,
  status      text NOT NULL,
  started_at  timestamptz NOT NULL,
  finished_at timestamptz NOT NULL,
  bill_rows   integer NOT NULL,
  matched     integer NOT NULL,
  diffs       integer NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT payout_recon_runs_pkey PRIMARY KEY (id),
  CONSTRAINT payout_recon_runs_day_key UNIQUE (app_id, channel, bill_date),
  CONSTRAINT payout_recon_runs_app_id_check CHECK (app_id <> ''),
  CONSTRAINT payout_recon_runs_channel_check CHECK (channel IN ('alipay')),
  CONSTRAINT payout_recon_runs_status_check CHECK (status IN ('succeeded', 'partial', 'failed')),
  CONSTRAINT payout_recon_runs_finished_at_check CHECK (finished_at >= started_at),
  CONSTRAINT payout_recon_runs_bill_rows_check CHECK (bill_rows >= 0),
  CONSTRAINT payout_recon_runs_matched_check CHECK (matched >= 0),
  CONSTRAINT payout_recon_runs_diffs_check CHECK (diffs >= 0)
);

GRANT SELECT, INSERT ON app.recon_channel TO couli_app;
GRANT UPDATE (our_status, channel_status, our_amount_fen, channel_amount_fen, result, updated_at)
  ON app.recon_channel TO couli_app;
GRANT SELECT ON app.recon_channel TO couli_payout;
GRANT SELECT ON app.recon_channel TO couli_readonly;

GRANT SELECT, INSERT ON app.payout_recon_runs TO couli_app;
GRANT UPDATE (status, started_at, finished_at, bill_rows, matched, diffs, updated_at)
  ON app.payout_recon_runs TO couli_app;
GRANT SELECT ON app.payout_recon_runs TO couli_payout;
GRANT SELECT ON app.payout_recon_runs TO couli_readonly;
