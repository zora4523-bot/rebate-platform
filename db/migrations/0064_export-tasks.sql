-- Up Migration
-- Back-office export tasks (contract CT-24k AdminExport and its status transitions; 规划/08 BR-ID-34
-- 细则「后台导出任务」, 24-hour download window). 规划/04 §3.2 has no row for this table yet; the shape
-- follows the task ledger note and the orchestrator ruling in the B1-34b brief §9. Task B1-34b.
-- Storage only: creation, the worker, cancellation on deactivation and expiry cleanup are later
-- admin tasks.
-- Compatibility: additive. One new ordinary table in schema app with named constraints, four
-- indexes and grants; no existing object changes (the foreign key only takes a SHARE ROW EXCLUSIVE
-- lock on admin_users while it is added).
-- Recovery: restore from backup; no down migration. (Rolling back is a later migration that drops
-- app.export_tasks once no reader uses it; it is not a funds or attribution table.)
--
-- app.export_tasks: one row per export request.
--   id: UUIDv7 generated by the application; no column default.
--   public_id: opaque external id generated by the application, unique per app; never the
--     internal id. No column default.
--   resource: users / audit_logs.
--   filters / filters_summary: request parameters as submitted and their display summary.
--   masked: whether the file masks personal data; audit-log exports must always be masked.
--   created_by: requesting admin (foreign key to admin_users (app_id, id), no cascade).
--   status: pending / running / done / failed / expired / cancelled. No default: the application
--     writes 'pending' explicitly on insert.
--   progress (0–100), failure_reason, file_name, object_key, row_count (>= 0), generated_at and
--     expires_at: worker results, all nullable. Deliberately no cross-column CHECK tying them to
--     status (the state machine lives in the application, contract transitions).
--   row_version: optimistic version, starts at 1.
-- No business instant has a SQL clock default: generated_at and expires_at come from the injected
-- Clock (expires_at = generated_at + 24 hours is computed by the application, not here).
--
-- Indexes: (app_id, created_at) for the list; (app_id, created_by, created_at) for "my exports";
-- partial (app_id, created_by, created_at) WHERE status IN ('pending', 'running') to cancel a
-- deactivated admin's active tasks and to schedule; partial (app_id, expires_at) WHERE
-- status = 'done' for the expiry sweep. Predicates reference status only.
--
-- Grants (one GRANT per role): couli_app SELECT, INSERT and column-level UPDATE on the worker /
-- lifecycle columns only (identity, public id, resource, filters, masking, creator and created_at
-- are never updatable); no DELETE, TRUNCATE, REFERENCES or TRIGGER for anyone. couli_readonly
-- SELECT.
--
-- Timeouts: one new empty table, one foreign key (SHARE ROW EXCLUSIVE lock on admin_users while it
-- is added) and four indexes on an empty table; 5s lock wait so a blocked deploy fails fast, 30s
-- overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.export_tasks (
  id               uuid        NOT NULL,
  app_id           text        NOT NULL,
  public_id        text        NOT NULL,
  resource         text        NOT NULL,
  filters          jsonb       NOT NULL,
  filters_summary  text        NOT NULL,
  masked           boolean     NOT NULL,
  created_by       uuid        NOT NULL,
  status           text        NOT NULL,
  progress         integer,
  failure_reason   text,
  file_name        text,
  object_key       text,
  row_count        integer,
  generated_at     timestamptz,
  expires_at       timestamptz,
  row_version      integer     NOT NULL DEFAULT 1,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT export_tasks_pkey PRIMARY KEY (id),
  CONSTRAINT export_tasks_app_id_public_id_key UNIQUE (app_id, public_id),
  CONSTRAINT export_tasks_created_by_fkey FOREIGN KEY (app_id, created_by)
    REFERENCES app.admin_users (app_id, id),
  CONSTRAINT export_tasks_resource_check CHECK (resource IN ('users', 'audit_logs')),
  -- Audit-log exports can never be plain text.
  CONSTRAINT export_tasks_audit_masked_check CHECK (resource <> 'audit_logs' OR masked),
  CONSTRAINT export_tasks_status_check
    CHECK (status IN ('pending', 'running', 'done', 'failed', 'expired', 'cancelled')),
  CONSTRAINT export_tasks_progress_check CHECK (progress IS NULL OR progress BETWEEN 0 AND 100),
  CONSTRAINT export_tasks_row_count_check CHECK (row_count IS NULL OR row_count >= 0)
);

CREATE INDEX export_tasks_app_created_idx
  ON app.export_tasks (app_id, created_at);

CREATE INDEX export_tasks_creator_created_idx
  ON app.export_tasks (app_id, created_by, created_at);

CREATE INDEX export_tasks_creator_active_idx
  ON app.export_tasks (app_id, created_by, created_at)
  WHERE status IN ('pending', 'running');

CREATE INDEX export_tasks_done_expires_idx
  ON app.export_tasks (app_id, expires_at)
  WHERE status = 'done';

GRANT SELECT, INSERT,
  UPDATE (status, progress, failure_reason, file_name, object_key, row_count, generated_at,
    expires_at, row_version, updated_at)
  ON app.export_tasks TO couli_app;
GRANT SELECT ON app.export_tasks TO couli_readonly;
