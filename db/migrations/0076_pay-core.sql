CREATE TABLE app.pay_query_attempts (
  id            uuid NOT NULL,
  app_id        text NOT NULL,
  pay_order_id  uuid,
  pay_refund_id uuid,
  kind          text NOT NULL,
  request       jsonb,
  response      jsonb,
  result        text,
  at            timestamptz NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT pay_query_attempts_pkey PRIMARY KEY (id),
  CONSTRAINT pay_query_attempts_order_fkey FOREIGN KEY (app_id, pay_order_id)
    REFERENCES app.pay_orders (app_id, id),
  CONSTRAINT pay_query_attempts_refund_fkey FOREIGN KEY (app_id, pay_refund_id)
    REFERENCES app.pay_refunds (app_id, id),
  CONSTRAINT pay_query_attempts_target_check CHECK (num_nonnulls(pay_order_id, pay_refund_id) = 1),
  CONSTRAINT pay_query_attempts_kind_check
    CHECK (kind IN ('query', 'close', 'refund', 'refund_query'))
);

CREATE INDEX pay_query_attempts_order_at_idx ON app.pay_query_attempts (app_id, pay_order_id, at);
CREATE INDEX pay_query_attempts_refund_at_idx
  ON app.pay_query_attempts (app_id, pay_refund_id, at);

CREATE TRIGGER pay_query_attempts_append_only
  BEFORE UPDATE OR DELETE ON app.pay_query_attempts
  FOR EACH ROW EXECUTE FUNCTION app.reject_update_delete();

