-- Up Migration
-- Payment core tables (BR-PAY-02 支付单、单号与状态机, BR-PAY-04 支付结果判定, BR-PAY-05 关单与异常收款,
-- BR-PAY-06 退款; 规划/04 §3.2 pay_orders, pay_notifications, pay_query_attempts, pay_refunds,
-- pay_anomalies, pay_fulfillments (couli #179, D10-168 ②)). Task B2-15a. Storage only: state
-- transitions, ledger vouchers and the invariant SQL belong to later tasks (B2-15b…, B2-15j).
-- Compatibility: additive. Six new empty tables, named constraints / indexes, two immutable-column
-- guard functions with their triggers, two append-only guard triggers, grants.
-- Recovery: restore from backup; no down migration.
--
-- Common: every table has id uuid (generated by the application, no default) and app_id text NOT
-- NULL; foreign keys carry app_id (no cross-app rows), are named and never cascade. Money columns
-- are bigint fen. Business times have no database default; created_at defaults to now() only as
-- the technical insert time. Enumerations follow the payment contract (CT-21b) and are CHECKs.
--
-- pay_orders: one order per (app_id, out_trade_no), never released, closed orders included.
--   out_trade_no is 1–32 ASCII letters / digits (the intersection of the WeChat Pay and Alipay
--   limits). amount_fen > 0; refunded_fen in [0, amount_fen] (refunds never change status; the
--   "refunded" labels are derived from refunded_fen). status is PENDING / PAID / CLOSED; at most
--   one PENDING or PAID order per business object (app_id, biz_type, biz_ref), enforced by a
--   partial unique index so concurrent creation is decided by PostgreSQL. UNIQUE (app_id, id) is
--   the target of the app-scoped foreign keys. out_trade_no, amount_fen, pay_channel, biz_type,
--   biz_ref and user_id (and id, app_id) can never change: a BEFORE UPDATE row trigger rejects it
--   for every role, on top of the column grants.
-- pay_notifications: raw channel notifications, insert-only, deduplicated on
--   (app_id, pay_channel, notify_id). payload_cipher is the FieldCrypto ciphertext of the original
--   body. At least one of out_trade_no / out_refund_no is set. No foreign key: a notification for
--   an unknown merchant number must still be kept as evidence.
-- pay_query_attempts: one row per query / close / refund / refund-query call, insert-only; exactly
--   one of pay_order_id / pay_refund_id is set. request, response and result stay nullable for
--   calls whose outcome is unknown.
-- pay_refunds: one refund per (app_id, out_refund_no) and per (app_id, idempotency_key); the target
--   is a pay_order or a pay_anomaly (polymorphic, so target_id has no foreign key). out_refund_no,
--   amount_fen, target_type and target_id can never change (trigger as for pay_orders).
-- pay_anomalies: receipts the channel proves for a CLOSED order or an unknown merchant number,
--   unique on (app_id, pay_channel, channel_trade_no); pay_order_id is NULL when we have no order.
--   status (agent default): open = not fully refunded, refunded = fully returned, closed = closed
--   manually.
-- pay_fulfillments: business fulfilment state per business object (app_id, biz_type, biz_ref);
--   version is the optimistic-lock counter.
-- Retention: none here.
--
-- Grants: couli_app only. SELECT, INSERT on all six tables; UPDATE only on the mutable columns of
-- pay_orders, pay_refunds, pay_anomalies and pay_fulfillments; no UPDATE / DELETE on the two
-- insert-only tables, whose app.reject_update_delete() triggers (0003) reject UPDATE and DELETE
-- for every role as a second line of defence. couli_readonly SELECT. couli_payout and couli_maint
-- get nothing (BR-PAY-08 ①: payouts cannot read payment data).
--
-- Timeouts: only new, empty tables and two new functions are created; short catalog locks only.
-- 5s lock wait so a blocked deploy fails fast, 30s overall as a ceiling.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE app.pay_orders (
  id               uuid NOT NULL,
  app_id           text NOT NULL,
  user_id          uuid NOT NULL,
  biz_type         text NOT NULL,
  biz_ref          text NOT NULL,
  pay_channel      text NOT NULL,
  amount_fen       bigint NOT NULL,
  refunded_fen     bigint NOT NULL DEFAULT 0,
  status           text NOT NULL,
  out_trade_no     text NOT NULL,
  channel_trade_no text,
  expire_at        timestamptz NOT NULL,
  launch_issued_at timestamptz,
  closing          boolean NOT NULL DEFAULT false,
  needs_manual     boolean NOT NULL DEFAULT false,
  paid_at          timestamptz,
  closed_at        timestamptz,
  close_reason     text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL,
  CONSTRAINT pay_orders_pkey PRIMARY KEY (id),
  CONSTRAINT pay_orders_app_id_id_key UNIQUE (app_id, id),
  CONSTRAINT pay_orders_out_trade_no_key UNIQUE (app_id, out_trade_no),
  CONSTRAINT pay_orders_user_fkey FOREIGN KEY (app_id, user_id)
    REFERENCES app.users (app_id, id),
  CONSTRAINT pay_orders_biz_type_check CHECK (biz_type <> ''),
  CONSTRAINT pay_orders_biz_ref_check CHECK (biz_ref <> ''),
  CONSTRAINT pay_orders_pay_channel_check CHECK (pay_channel IN ('wechat_pay', 'alipay')),
  CONSTRAINT pay_orders_amount_fen_check CHECK (amount_fen > 0),
  CONSTRAINT pay_orders_refunded_fen_check
    CHECK (refunded_fen >= 0 AND refunded_fen <= amount_fen),
  CONSTRAINT pay_orders_status_check CHECK (status IN ('PENDING', 'PAID', 'CLOSED')),
  CONSTRAINT pay_orders_out_trade_no_check CHECK (out_trade_no ~ '^[A-Za-z0-9]{1,32}$')
);

-- At most one open (PENDING or PAID) order per business object (BR-PAY-02).
CREATE UNIQUE INDEX pay_orders_open_biz_key
  ON app.pay_orders (app_id, biz_type, biz_ref) WHERE status IN ('PENDING', 'PAID');
CREATE INDEX pay_orders_user_created_idx ON app.pay_orders (app_id, user_id, created_at);
CREATE INDEX pay_orders_status_expire_idx ON app.pay_orders (app_id, status, expire_at);

CREATE FUNCTION app.pay_orders_reject_immutable_update()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, pg_temp
AS $$
BEGIN
  IF NEW.id IS DISTINCT FROM OLD.id
    OR NEW.app_id IS DISTINCT FROM OLD.app_id
    OR NEW.out_trade_no IS DISTINCT FROM OLD.out_trade_no
    OR NEW.amount_fen IS DISTINCT FROM OLD.amount_fen
    OR NEW.pay_channel IS DISTINCT FROM OLD.pay_channel
    OR NEW.biz_type IS DISTINCT FROM OLD.biz_type
    OR NEW.biz_ref IS DISTINCT FROM OLD.biz_ref
    OR NEW.user_id IS DISTINCT FROM OLD.user_id
  THEN
    RAISE EXCEPTION 'pay_orders out_trade_no, amount_fen, pay_channel, biz_type, biz_ref and user_id cannot be changed'
      USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END
$$;

REVOKE ALL ON FUNCTION app.pay_orders_reject_immutable_update() FROM PUBLIC;

CREATE TRIGGER pay_orders_immutable_columns
  BEFORE UPDATE ON app.pay_orders
  FOR EACH ROW EXECUTE FUNCTION app.pay_orders_reject_immutable_update();

