import { accountingDate, chinaMonth } from '@couli/domain';
import { expect, it } from 'vitest';

// B1-08d 编排补充：固定 +08:00，自然月归月不推导 settle_period。
// AC-B1-08d 为本任务测试追踪号；不是新增业务验收条款。
const instants = [
  ['2026-10-19T15:59:59.999Z', '2026-10-19', '2026-10'],
  ['2026-10-19T16:00:00.000Z', '2026-10-20', '2026-10'],
  ['2026-10-19T16:10:00.000Z', '2026-10-20', '2026-10'],
  ['2026-10-19T23:59:59.999Z', '2026-10-20', '2026-10'],
  ['2026-10-20T00:00:00.000Z', '2026-10-20', '2026-10'],
  ['2026-10-31T15:59:59.999Z', '2026-10-31', '2026-10'],
  ['2026-10-31T16:00:00.000Z', '2026-11-01', '2026-11'],
  ['2026-12-31T15:59:59.999Z', '2026-12-31', '2026-12'],
  ['2026-12-31T16:00:00.000Z', '2027-01-01', '2027-01'],
  ['2024-02-28T15:59:59.999Z', '2024-02-28', '2024-02'],
  ['2024-02-28T16:00:00.000Z', '2024-02-29', '2024-02'],
  ['2024-02-29T15:59:59.999Z', '2024-02-29', '2024-02'],
  ['2024-02-29T16:00:00.000Z', '2024-03-01', '2024-03'],
  ['2026-02-28T16:00:00.000Z', '2026-03-01', '2026-03'],
  ['1969-12-31T15:59:59.999Z', '1969-12-31', '1969-12'],
  ['1969-12-31T16:00:00.000Z', '1970-01-01', '1970-01'],
  ['0099-01-01T00:00:00.000Z', '0099-01-01', '0099-01'],
  // Asia/Shanghai 在 1991 年夏季有夏令时；规则要求固定 +08:00。
  ['1991-06-30T15:30:00.000Z', '1991-06-30', '1991-06'],
] as const;

it.each(instants)('[AC-B1-08d#1] accountingDate：%s → %s', (iso, date) => {
  expect(accountingDate(new Date(iso))).toBe(date);
});

it.each(instants)('[AC-B1-08d#2] chinaMonth：%s 归入对应自然月', (iso, _date, month) => {
  expect(chinaMonth(new Date(iso))).toBe(month);
});

it.each(['2026-10-20T00:10:00+08:00', '2026-10-19T16:10:00Z', '2026-10-19T09:10:00-07:00'])(
  '[AC-B1-08d#3] 同一绝对时刻 %s 的日期与月份一致',
  (iso) => {
    const at = new Date(iso);
    expect([accountingDate(at), chinaMonth(at)]).toEqual(['2026-10-20', '2026-10']);
  },
);

it('[AC-B1-08d#4] 格式化不修改传入 Date，交错调用后结果不变', () => {
  const at = new Date('2026-12-31T15:59:59.999Z');
  const before = at.getTime();
  const first = [accountingDate(at), chinaMonth(at)];
  accountingDate(new Date('2024-02-29T16:00:00Z'));
  chinaMonth(new Date('2024-02-29T16:00:00Z'));
  expect({ first, again: [accountingDate(at), chinaMonth(at)], instant: at.getTime() }).toEqual({
    first: ['2026-12-31', '2026-12'],
    again: ['2026-12-31', '2026-12'],
    instant: before,
  });
});
