import { inviteFailWindow } from '@couli/domain';
import { expect, it } from 'vitest';

it.each([
  ['2026-10-17T00:00:00+08:00', '2026-10-17', 86400],
  ['2026-10-17T00:00:00.001+08:00', '2026-10-17', 86400],
  ['2026-10-17T07:59:59+08:00', '2026-10-17', 57601],
  ['2026-10-17T08:00:00+08:00', '2026-10-17', 57600],
  ['2026-10-17T23:59:58.999+08:00', '2026-10-17', 2],
  ['2026-10-17T23:59:59.000+08:00', '2026-10-17', 1],
  ['2026-10-17T23:59:59.001+08:00', '2026-10-17', 1],
  ['2026-10-17T23:59:59.999+08:00', '2026-10-17', 1],
  ['2026-10-16T16:00:00Z', '2026-10-17', 86400],
  ['2026-10-16T15:59:59Z', '2026-10-16', 1],
  ['2026-10-31T23:59:59.999+08:00', '2026-10-31', 1],
  ['2026-11-01T00:00:00+08:00', '2026-11-01', 86400],
  ['2026-12-31T23:59:59.999+08:00', '2026-12-31', 1],
  ['2027-01-01T00:00:00+08:00', '2027-01-01', 86400],
  ['2028-02-28T23:59:59.999+08:00', '2028-02-28', 1],
  ['2028-02-29T00:00:00+08:00', '2028-02-29', 86400],
  ['2028-02-29T23:59:59.999+08:00', '2028-02-29', 1],
  ['2028-03-01T00:00:00+08:00', '2028-03-01', 86400],
  ['1969-12-31T23:59:59.999+08:00', '1969-12-31', 1],
  ['2026-10-16T12:00:00-04:00', '2026-10-17', 86400],
] as const)(
  '[AC-B1-11c#16] BR-INV-02 %s → 北京日键 %s、Retry-After %s 秒，保留入参',
  (iso, day, seconds) => {
    const now = new Date(iso);
    expect(inviteFailWindow(now)).toEqual({ day, retry_after_seconds: seconds });
    expect(now.getTime()).toBe(Date.parse(iso));
  },
);

it.each([NaN, Infinity, -Infinity])('[AC-B1-11c#17] 非法时刻 %s 不生成频控键', (value) => {
  expect(() => inviteFailWindow(new Date(value))).toThrow(RangeError);
});
