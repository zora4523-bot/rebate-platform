// Storage shape of app.personal_data_copies: 04 §3.2, §2.5; BR-ID-40; 任务书 §9 ①–③.
import { createTestDatabase } from '@couli/db/testing';
import { afterAll, beforeAll, expect, it } from 'vitest';

import {
  COPIES,
  close,
  constraints,
  expectedShape,
  indexes,
  open,
  ready,
  shape,
  type Harness,
} from './kit.ts';

let h: Harness;
beforeAll(async () => {
  h = open(await createTestDatabase());
});
afterAll(async () => {
  await close(h);
});

it('[AC-B1-27d#1] columns have the specified types, nullability and defaults, and nothing else', async () => {
  await ready(h.app, COPIES);
  // id is the external number (export_id / copy_id, contract Id = UUIDv7) generated by the
  // application; no business instant has a SQL clock default.
  expect(await shape(h.app, COPIES)).toEqual(
    expectedShape([
      ['id', 'uuid', false, null],
      ['app_id', 'text', false, null],
      ['user_id', 'uuid', false, null],
      ['requested_by', 'uuid', false, null],
      ['delivery', 'text', false, null],
      ['status', 'text', false, null],
      ['retry_of', 'uuid', true, null],
      ['object_key', 'text', true, null],
      ['due_at', 'timestamptz', false, null],
      ['generated_at', 'timestamptz', true, null],
      ['delivered_at', 'timestamptz', true, null],
      ['expires_at', 'timestamptz', true, null],
      ['failure_reason', 'text', true, null],
      ['row_version', 'int4', false, '0'],
      ['created_at', 'timestamptz', false, 'now()'],
      ['updated_at', 'timestamptz', false, 'now()'],
    ]),
  );
});

it('[AC-B1-27d#2] no column stores the reason, identity check, channel facts, extraction code or password', async () => {
  await ready(h.app, COPIES);
  const names = (await shape(h.app, COPIES)).map((c) => c.name);
  for (const name of names) {
    if (name === 'failure_reason') continue;
    expect(name).not.toMatch(/reason|identity|verif|login_ok|sms_ok|channel|code|pass|secret|pin/);
  }
});

it('[AC-B1-27d#3] primary key on id; user, registrant and retry_of foreign keys are tenant-qualified and never cascade', async () => {
  await ready(h.app, COPIES);
  const found = await constraints(h.app, COPIES);
  expect(found.filter((c) => c.kind === 'p').map((c) => c.keys)).toEqual([['id']]);
  const foreign = found.filter((c) => c.kind === 'f');
  const pick = (target: string, column: string) =>
    foreign.filter((c) => c.target === target && c.keys.includes(column));
  for (const [target, column, keys, targetKeys] of [
    ['app.users', 'user_id', ['app_id', 'user_id'], ['app_id', 'id']],
    ['app.admin_users', 'requested_by', ['app_id', 'requested_by'], ['app_id', 'id']],
    ['app.personal_data_copies', 'retry_of', ['app_id', 'retry_of'], ['app_id', 'id']],
  ] as const) {
    const matches = pick(target, column);
    expect(matches, `${column} -> ${target}`).toHaveLength(1);
    expect(matches[0]).toMatchObject({ keys, target_keys: targetKeys, validated: true });
  }
  expect(foreign).toHaveLength(3);
  for (const fk of foreign) {
    expect(['a', 'r'], `${fk.keys.join(',')} on update`).toContain(fk.on_update);
    expect(['a', 'r'], `${fk.keys.join(',')} on delete`).toContain(fk.on_delete);
  }
});

it('[AC-B1-27d#4] a valid partial unique index on (app_id, user_id) covers exactly the unfinished statuses', async () => {
  await ready(h.app, COPIES);
  const slots = (await indexes(h.app, COPIES)).filter(
    (i) => i.unique && i.predicate !== null && i.keys.join(',') === 'app_id,user_id',
  );
  expect(slots).toHaveLength(1);
  expect(slots[0]).toMatchObject({ expression: false, valid: true });
  const predicate = slots[0]!.predicate!;
  for (const status of ['pending', 'running', 'ready']) {
    expect(predicate).toContain(`'${status}'`);
  }
  for (const status of ['delivered', 'failed', 'expired', 'cancelled']) {
    expect(predicate).not.toContain(`'${status}'`);
  }
});
